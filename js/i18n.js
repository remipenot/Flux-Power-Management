  var lang = "fr";

  function fill(text, vars) {
    if (!vars) return text;
    return String(text).replace(/\{(\w+)\}/g, function (_m, key) {
      return vars[key] == null ? "" : String(vars[key]);
    });
  }

  function t(key, vars) {
    var pack = STR[lang] || STR.fr;
    var text = pack[key];
    if (text == null) text = STR.fr[key];
    if (text == null) text = key;
    return fill(text, vars);
  }

  function apply() {
    if (typeof document === "undefined" || !document.querySelectorAll) return;
    document.documentElement.lang = lang === "en" ? "en" : "fr";
    document.title = t("docTitle");
    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    document.querySelectorAll("[data-i18n-title]").forEach(function (el) {
      el.title = t(el.getAttribute("data-i18n-title"));
    });
    document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
      el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
    });
    document.querySelectorAll("[data-lang]").forEach(function (btn) {
      btn.classList.toggle("on", btn.getAttribute("data-lang") === lang);
    });
  }

  function setLang(next) {
    lang = next === "en" ? "en" : "fr";
    try { localStorage.setItem("flux-lang", lang); } catch (err) { /* private mode */ }
    apply();
    if (global.PowerUI && typeof global.PowerUI.refresh === "function") global.PowerUI.refresh();
  }

  function boot() {
    var query = "";
    try {
      if (typeof location !== "undefined" && location.search) {
        query = new URLSearchParams(location.search).get("lang") || "";
      }
    } catch (err) { query = ""; }
    var stored = "";
    try { stored = localStorage.getItem("flux-lang") || ""; } catch (err) { stored = ""; }
    if (query === "en" || query === "fr") lang = query;
    else if (stored === "en" || stored === "fr") lang = stored;
    else lang = "fr";
    apply();
    if (typeof document !== "undefined" && document.querySelectorAll) {
      document.querySelectorAll("[data-lang]").forEach(function (btn) {
        btn.addEventListener("click", function () { setLang(btn.getAttribute("data-lang")); });
      });
    }
  }

  global.FluxI18n = { t: t, setLang: setLang, apply: apply, lang: function () { return lang; } };

  if (typeof document !== "undefined") {
    if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", boot);
    else boot();
  }
